interface AtlasEntry {
  x: number;
  y: number;
  width: number;
  height: number;
  drawOffsetX: number;
  drawOffsetY: number;
  frameWidth: number;
  frameHeight: number;
}

interface GameAssets {
  image: HTMLCanvasElement;
  entries: Record<string, AtlasEntry>;
  keys: string[];
  frameLists: Map<string, string[]>;
  tinted: Map<string, HTMLCanvasElement>;
}

interface AnimationChoice {
  prefix: string;
  delay: number;
  indices?: number[];
}

let assetsPromise: Promise<GameAssets> | null = null;

function imageToCanvas(image: HTMLImageElement): HTMLCanvasElement {
  const canvas = document.createElement("canvas");
  canvas.width = image.naturalWidth;
  canvas.height = image.naturalHeight;
  const context = canvas.getContext("2d");
  if (context) context.drawImage(image, 0, 0);
  return canvas;
}

function loadAssetImage(
  source: string,
  errorMessage: string,
): Promise<HTMLImageElement> {
  return new Promise<HTMLImageElement>((resolve, reject) => {
    const image = new Image();
    image.src = source;
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error(errorMessage));
  });
}

export function loadAssets(): Promise<GameAssets> {
  if (!assetsPromise) {
    assetsPromise = (async () => {
      // Shared base atlas: vanilla gameplay textures every theme falls back to
      // (default spikes, crystals, jumpthru, tilesets, chapter backdrops).
      const manifest = (await fetch(
        "/assets/original/gameplay/gameplay-selected.json",
      ).then((response) => response.json())) as {
        entries: Record<string, AtlasEntry>;
      };
      const image = await loadAssetImage(
        "/assets/original/gameplay/gameplay-selected.png",
        "无法加载基础游戏图集",
      );
      return {
        image: imageToCanvas(image),
        entries: manifest.entries,
        keys: Object.keys(manifest.entries),
        frameLists: new Map(),
        tinted: new Map(),
      };
    })();
  }
  return assetsPromise;
}

/** Load a single theme's small atlas (generated by extract-mod-themes.mjs). */
export async function loadThemeAtlas(
  atlasUrl: string,
): Promise<GameAssets> {
  const manifest = (await fetch(`/${atlasUrl}`).then((response) =>
    response.json(),
  )) as { entries: Record<string, AtlasEntry> };
  const image = await loadAssetImage(
    `/${atlasUrl.replace(/\.json$/, ".png")}`,
    `主题图集加载失败: ${atlasUrl}`,
  );
  return {
    image: imageToCanvas(image),
    entries: manifest.entries,
    keys: Object.keys(manifest.entries),
    frameLists: new Map(),
    tinted: new Map(),
  };
}

function mergeGameAssets(
  base: GameAssets,
  overlay: GameAssets,
): GameAssets {
  const image = document.createElement("canvas");
  image.width = Math.max(base.image.width, overlay.image.width);
  image.height = base.image.height + overlay.image.height;
  const context = image.getContext("2d");
  if (!context) return base;
  context.imageSmoothingEnabled = false;
  context.drawImage(base.image, 0, 0);
  context.drawImage(overlay.image, 0, base.image.height);
  const entries = {
    ...base.entries,
    ...Object.fromEntries(
      Object.entries(overlay.entries).map(([key, entry]) => [
        key,
        { ...entry, y: entry.y + base.image.height },
      ]),
    ),
  };
  // Fresh caches: the theme atlas loads asynchronously, and a frames() hit
  // against the base-only assets would otherwise cache an empty list that
  // survives the merge and hides every custom texture (the gym Orb, ...).
  return {
    image,
    entries,
    keys: Object.keys(entries),
    frameLists: new Map(),
    tinted: new Map(),
  };
}

function frames(assets: GameAssets, prefix: string): string[] {
  const cached = assets.frameLists.get(prefix);
  if (cached) return cached;
  const found = atlasFrameKeys(assets.keys, prefix);
  assets.frameLists.set(prefix, found);
  return found;
}

function choosePlayerAnimation(state: SimState): AnimationChoice {
  if (state.dead) return { prefix: "characters/player/death_h", delay: 1 };
  if (state.state === "StarFly") {
    return state.star_fly_transforming ||
      (state.star_fly_transform_frames ?? 0) > 0
      ? { prefix: "characters/player/startStarFly", delay: 5 }
      : { prefix: "characters/player/starFly", delay: 5 };
  }
  if (state.state === "DreamDash")
    return {
      prefix: "characters/player/dreamDash",
      delay: 2,
      indices: Array.from({ length: 13 }, (_, index) => index + 4),
    };
  if (state.state === "Dash" || state.state === "RedDash")
    return { prefix: "characters/player/dash", delay: 5 };
  if (state.state === "Swim")
    return {
      prefix: "characters/player/swim",
      delay: 5,
      indices: [0, 1, 2, 3, 4, 5],
    };
  if (state.state === "SummitLaunch" || state.state === "Launch")
    return { prefix: "characters/player/launch", delay: 4 };
  if (state.state === "Climb")
    return {
      prefix: "characters/player/climb",
      delay: Math.abs(state.speed.y) > 5 ? 3 : 99,
      indices: Math.abs(state.speed.y) > 5 ? [0, 1, 2, 3, 4, 5] : [0],
    };
  if (state.ducking) return { prefix: "characters/player/duck", delay: 99 };
  if (!state.on_ground) {
    const prefix =
      Math.abs(state.speed.x) > 90
        ? "characters/player/jumpFast"
        : "characters/player/jumpSlow";
    return { prefix, delay: 6, indices: state.speed.y < 0 ? [0, 1] : [2, 3] };
  }
  if (Math.abs(state.speed.x) > 20)
    return {
      prefix:
        Math.abs(state.speed.x) > 70
          ? "characters/player/runFast"
          : "characters/player/runSlow",
      delay: Math.abs(state.speed.x) > 70 ? 3 : 4,
    };
  return { prefix: "characters/player/idle", delay: 6 };
}

function playerFrameKey(
  assets: GameAssets,
  state: SimState,
  frame: number,
): string | undefined {
  const animation = choosePlayerAnimation(state);
  const available = frames(assets, animation.prefix);
  const indices = animation.indices ?? available.map((_, index) => index);
  const animationIndex =
    indices[
      Math.floor(frame / animation.delay) % Math.max(1, indices.length)
    ] ?? 0;
  return available[animationIndex] ?? available[0];
}

function tintedEntry(
  assets: GameAssets,
  key: string,
  color: string,
): HTMLCanvasElement | undefined {
  const entry = assets.entries[key];
  if (!entry) return undefined;
  const cacheKey = `${key}:${color}`;
  const cached = assets.tinted.get(cacheKey);
  if (cached) return cached;
  const canvas = document.createElement("canvas");
  canvas.width = entry.width;
  canvas.height = entry.height;
  const context = canvas.getContext("2d");
  if (!context) return undefined;
  context.drawImage(
    assets.image,
    entry.x,
    entry.y,
    entry.width,
    entry.height,
    0,
    0,
    entry.width,
    entry.height,
  );
  context.globalCompositeOperation = "source-in";
  context.fillStyle = color;
  context.fillRect(0, 0, entry.width, entry.height);
  assets.tinted.set(cacheKey, canvas);
  return canvas;
}

function framedEntry(
  assets: GameAssets,
  key: string,
  tint?: string,
): HTMLCanvasElement | undefined {
  const entry = assets.entries[key];
  if (!entry) return undefined;
  const cacheKey = `frame:${key}:${tint ?? "original"}`;
  const cached = assets.tinted.get(cacheKey);
  if (cached) return cached;
  // Bounded LRU: animated rainbow hues change every frame and must not grow
  // the cache without limit (the old entries are still collected by the GC).
  if (assets.tinted.size >= 600) {
    const oldest = assets.tinted.keys().next().value;
    if (oldest !== undefined) assets.tinted.delete(oldest);
  }
  const canvas = document.createElement("canvas");
  canvas.width = entry.frameWidth;
  canvas.height = entry.frameHeight;
  const context = canvas.getContext("2d");
  if (!context) return undefined;
  context.drawImage(
    assets.image,
    entry.x,
    entry.y,
    entry.width,
    entry.height,
    entry.drawOffsetX,
    entry.drawOffsetY,
    entry.width,
    entry.height,
  );
  if (tint) {
    context.globalCompositeOperation = "source-in";
    context.fillStyle = tint;
    context.fillRect(0, 0, canvas.width, canvas.height);
  }
  assets.tinted.set(cacheKey, canvas);
  return canvas;
}

function dreamParticleTexture(
  assets: GameAssets,
  sourceX: number,
  color: string,
): HTMLCanvasElement | undefined {
  const entry = assets.entries["objects/dreamblock/particles"];
  if (!entry) return undefined;
  const cacheKey = `dream-particle:${sourceX}:${color}`;
  const cached = assets.tinted.get(cacheKey);
  if (cached) return cached;
  const canvas = document.createElement("canvas");
  canvas.width = 7;
  canvas.height = 7;
  const context = canvas.getContext("2d");
  if (!context) return undefined;
  context.drawImage(
    assets.image,
    entry.x,
    entry.y,
    entry.width,
    entry.height,
    entry.drawOffsetX - sourceX,
    entry.drawOffsetY,
    entry.width,
    entry.height,
  );
  context.globalCompositeOperation = "source-in";
  context.fillStyle = color;
  context.fillRect(0, 0, 7, 7);
  assets.tinted.set(cacheKey, canvas);
  return canvas;
}

function drawEntry(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  key: string | undefined,
  x: number,
  y: number,
  originX = 0,
  originY = 0,
  scaleX = 1,
  scaleY = 1,
  tint?: string,
  rotation = 0,
): void {
  if (!key) return;
  const entry = assets.entries[key];
  if (!entry) return;
  context.save();
  context.translate(Math.round(x), Math.round(y));
  context.rotate(rotation);
  context.scale(scaleX, scaleY);
  const source = tint ? tintedEntry(assets, key, tint) : undefined;
  if (source) {
    context.drawImage(
      source,
      -originX + entry.drawOffsetX,
      -originY + entry.drawOffsetY,
    );
  } else {
    context.drawImage(
      assets.image,
      entry.x,
      entry.y,
      entry.width,
      entry.height,
      -originX + entry.drawOffsetX,
      -originY + entry.drawOffsetY,
      entry.width,
      entry.height,
    );
  }
  context.restore();
}

function drawOutlinedEntry(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  key: string | undefined,
  x: number,
  y: number,
  originX: number,
  originY: number,
  scaleX = 1,
  scaleY = 1,
  rotation = 0,
): void {
  for (const [dx, dy] of [
    [-1, 0],
    [1, 0],
    [0, -1],
    [0, 1],
  ] as const) {
    drawEntry(
      context,
      assets,
      key,
      x + dx,
      y + dy,
      originX,
      originY,
      scaleX,
      scaleY,
      "#000000",
      rotation,
    );
  }
  drawEntry(
    context,
    assets,
    key,
    x,
    y,
    originX,
    originY,
    scaleX,
    scaleY,
    undefined,
    rotation,
  );
}

