function approach(from: Vec2, to: Vec2, amount: number): Vec2 {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  const distance = Math.hypot(dx, dy);
  if (distance <= amount || distance === 0) return { ...to };
  return {
    x: from.x + (dx / distance) * amount,
    y: from.y + (dy / distance) * amount,
  };
}

function hairRoot(state: SimState, key: string | undefined): Vec2 {
  const metadata = playerHairMetadata(key);
  const facing = state.facing ? 1 : -1;
  return {
    x: state.pos.x + metadata.offset.x * facing,
    y: state.pos.y - 9 + metadata.offset.y,
  };
}

function computeHairNodes(
  assets: GameAssets,
  states: readonly (SimState | undefined)[],
  state: SimState,
  frame: number,
  frameOffset = 0,
): Vec2[] {
  const start = Math.max(0, frame - 180);
  let nodes: Vec2[] | undefined;
  for (let value = start; value <= frame; value += 1) {
    const sample =
      states[value - frameOffset] ?? (value === frame ? state : undefined);
    if (!sample) continue;
    const key = playerFrameKey(assets, sample, value);
    const root = hairRoot(sample, key);
    const facing = sample.facing ? 1 : -1;
    if (!nodes)
      nodes = Array.from({ length: 4 }, (_, index) => ({
        x: root.x - facing * index * 0.5,
        y: root.y + index * 2,
      }));
    nodes[0] = root;
    let target = { x: root.x - facing, y: root.y + 2 };
    let previous = root;
    for (let index = 1; index < 4; index += 1) {
      if (sample.state !== "StarFly") {
        const amount = ((1 - (index / 4) * 0.5) * 64) / 60;
        nodes[index] = approach(nodes[index], target, amount);
      }
      const distance = Math.hypot(
        nodes[index].x - previous.x,
        nodes[index].y - previous.y,
      );
      if (distance > 3) nodes[index] = approach(previous, nodes[index], 3);
      target = { x: nodes[index].x - facing * 0.5, y: nodes[index].y + 2 };
      previous = nodes[index];
    }
  }
  return (
    nodes ??
    Array.from({ length: 4 }, (_, index) => ({
      x: state.pos.x,
      y: state.pos.y - 11 + index * 2,
    }))
  );
}

function hairColor(state: SimState): string {
  if (state.state === "StarFly") return "#ffd65c";
  if (state.dashes === 0) return "#44b7ff";
  if (state.dashes >= 2) return "#ff6def";
  return "#ac3232";
}

function drawPlayer(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  states: readonly (SimState | undefined)[],
  state: SimState,
  frame: number,
  frameOffset = 0,
): void {
  const key = playerFrameKey(assets, state, frame);
  const facing = state.facing ? 1 : -1;
  context.save();
  context.globalAlpha = state.dead ? 0.75 : 1;
  if (!state.dead) {
    const nodes = computeHairNodes(assets, states, state, frame, frameOffset);
    const metadata = playerHairMetadata(key);
    for (let index = 3; index >= 0; index -= 1) {
      const texture =
        index === 0
          ? `characters/player/bangs0${metadata.frame}`
          : "characters/player/hair00";
      const scale = 0.25 + (1 - index / 4) * 0.75;
      const scaleX = index === 0 ? facing : scale;
      const scaleY = index === 0 ? 1 : scale;
      for (const [dx, dy] of [
        [-1, 0],
        [1, 0],
        [0, -1],
        [0, 1],
      ] as const) {
        drawEntry(
          context,
          assets,
          texture,
          nodes[index].x + dx,
          nodes[index].y + dy,
          5,
          5,
          scaleX,
          scaleY,
          "#000000",
        );
      }
      drawEntry(
        context,
        assets,
        texture,
        nodes[index].x,
        nodes[index].y,
        5,
        5,
        scaleX,
        scaleY,
        hairColor(state),
      );
    }
  }
  drawEntry(context, assets, key, state.pos.x, state.pos.y, 16, 32, facing, 1);
  context.restore();
}

function drawPlayerTrail(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  states: readonly (SimState | undefined)[],
  frame: number,
  frameOffset = 0,
): void {
  for (const sample of playerTrailSamples(states, frame, frameOffset)) {
    const state = states[sample.frame - frameOffset];
    if (!state) continue;
    const key = playerFrameKey(assets, state, sample.frame);
    const facing = state.facing ? 1 : -1;
    const color = playerTrailColor(state);
    context.save();
    context.globalAlpha = playerTrailOpacity(sample.age);
    const nodes = computeHairNodes(
      assets,
      states,
      state,
      sample.frame,
      frameOffset,
    );
    const metadata = playerHairMetadata(key);
    for (let index = 3; index >= 0; index -= 1) {
      const texture =
        index === 0
          ? `characters/player/bangs0${metadata.frame}`
          : "characters/player/hair00";
      const scale = 0.25 + (1 - index / 4) * 0.75;
      drawEntry(
        context,
        assets,
        texture,
        nodes[index].x,
        nodes[index].y,
        5,
        5,
        index === 0 ? facing : scale,
        index === 0 ? 1 : scale,
        color,
      );
    }
    drawEntry(
      context,
      assets,
      key,
      state.pos.x,
      state.pos.y,
      16,
      32,
      facing,
      1,
      color,
    );
    context.restore();
  }
}

function drawPlayerParticles(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  states: readonly (SimState | undefined)[],
  frame: number,
  frameOffset = 0,
): void {
  for (const particle of playerParticleSamples(states, frame, frameOffset)) {
    const directionAngle = Math.atan2(
      particle.direction.y,
      particle.direction.x,
    );
    if (particle.kind === "slash") {
      const key = `effects/slash/0${Math.min(3, Math.floor(particle.age / 3))}`;
      const entry = assets.entries[key];
      if (!entry) continue;
      context.save();
      context.globalAlpha = Math.max(0, 1 - particle.age / 12);
      drawEntry(
        context,
        assets,
        key,
        particle.origin.x,
        particle.origin.y,
        entry.frameWidth / 2,
        entry.frameHeight / 2,
        1,
        1,
        undefined,
        directionAngle,
      );
      context.restore();
      continue;
    }

    for (let index = 0; index < particle.count; index += 1) {
      const seed = particle.frame * 97.13 + index * 19.71;
      const radial =
        particle.kind === "death-shard"
          ? (index / particle.count) * Math.PI * 2
          : directionAngle;
      const spread = (pseudo(seed) - 0.5) *
        (particle.kind === "dust"
          ? 1.5
          : particle.kind === "water-splash"
            ? 2.2
            : 0.45);
      const angle = radial + spread;
      const speed =
        particle.kind === "dust"
          ? 18 + pseudo(seed + 3.1) * 34
          : particle.kind === "death-shard"
            ? 28 + pseudo(seed + 7.3) * 38
            : particle.kind === "water-splash"
              ? 32 + pseudo(seed + 7.3) * 42
              : 20 + pseudo(seed + 7.3) * 18;
      const seconds = particle.age / 60;
      const travel = speed * seconds;
      const wobble =
        particle.kind === "bubble" || particle.kind === "feather"
          ? Math.sin(particle.age * 0.35 + seed) * 1.5
          : 0;
      const x = particle.origin.x + Math.cos(angle) * travel + wobble;
      const y =
        particle.origin.y +
        Math.sin(angle) * travel +
        (particle.kind === "dust"
          ? 45 * seconds * seconds
          : particle.kind === "death-shard"
            ? 70 * seconds * seconds
            : particle.kind === "water-splash"
              ? 90 * seconds * seconds
              : particle.kind === "bubble"
                ? -12 * seconds
                : 0);
      const lifetime =
        particle.kind === "death-shard"
          ? 36
          : particle.kind === "dash-streak"
            ? 14
            : 24;
      const alpha = Math.max(0, 1 - particle.age / lifetime);
      const key =
        particle.kind === "dust"
          ? "particles/cloud"
          : particle.kind === "bubble"
            ? "particles/bubble"
            : particle.kind === "death-shard" ||
                particle.kind === "dream-spark"
              ? "particles/shard"
              : particle.kind === "feather"
                ? "particles/feather"
                : particle.kind === "water-splash"
                  ? index % 2 === 0
                    ? "particles/circle"
                    : "particles/cloud"
                  : "particles/rect";
      const entry = assets.entries[key];
      if (!entry) continue;
      const scale =
        particle.kind === "dust"
          ? 0.35 + pseudo(seed + 11.9) * 0.35
          : particle.kind === "bubble"
            ? 0.4 + pseudo(seed + 11.9) * 0.25
            : particle.kind === "water-splash"
              ? 0.35 + pseudo(seed + 11.9) * 0.35
              : 0.55;
      const tint =
        particle.kind === "dream-spark"
          ? ["#ff68d9", "#67e8ff", "#ffe36e"][index % 3]
          : particle.kind === "death-shard" && index % 3 === 0
            ? "#ffffff"
            : particle.color;
      context.save();
      context.globalAlpha = alpha;
      drawEntry(
        context,
        assets,
        key,
        x,
        y,
        entry.frameWidth / 2,
        entry.frameHeight / 2,
        scale,
        scale,
        tint,
        particle.kind === "dash-streak"
          ? directionAngle
          : particle.kind === "death-shard" ||
              particle.kind === "dream-spark" ||
              particle.kind === "feather"
            ? angle + particle.age * 0.12
            : 0,
      );
      context.restore();
    }
  }
}

function buildSolidGrid(map: GymMap): string[][] {
  if (map.tile_grid && map.tile_grid.length > 0) {
    const columns = Math.max(...map.tile_grid.map((row) => row.length), 1);
    return map.tile_grid.map((row) => {
      const cells = row.split("");
      while (cells.length < columns) cells.push("0");
      return cells.map((cell) => (cell === " " ? "0" : cell));
    });
  }
  const columns = Math.ceil(map.bounds.width / 8);
  const rows = Math.ceil(map.bounds.height / 8);
  const grid = Array.from({ length: rows }, () =>
    Array.from({ length: columns }, () => "0"),
  );
  for (const solid of map.solids) {
    const left = Math.max(0, Math.floor((solid.x - map.bounds.x) / 8));
    const top = Math.max(0, Math.floor((solid.y - map.bounds.y) / 8));
    const right = Math.min(
      columns,
      Math.ceil((solid.x + solid.width - map.bounds.x) / 8),
    );
    const bottom = Math.min(
      rows,
      Math.ceil((solid.y + solid.height - map.bounds.y) / 8),
    );
    for (let y = top; y < bottom; y += 1)
      for (let x = left; x < right; x += 1) grid[y][x] = "1";
  }
  return grid;
}

function tileCoordinate(
  grid: string[][],
  x: number,
  y: number,
): [number, number] {
  const filled = (dx: number, dy: number) =>
    grid[y + dy]?.[x + dx] !== undefined && grid[y + dy][x + dx] !== "0";
  const top = filled(0, -1);
  const bottom = filled(0, 1);
  const left = filled(-1, 0);
  const right = filled(1, 0);
  const variant = Math.abs(x * 17 + y * 31) % 4;
  if (!top && bottom && left && right) return [variant, 0];
  if (top && !bottom && left && right) return [variant, 1];
  if (top && bottom && !left && right) return [variant, 2];
  if (top && bottom && left && !right) return [variant, 3];
  if (!top && !bottom && left && right) return [variant, 4];
  if (top && bottom && !left && !right) return [variant, 5];
  if (!top && bottom && !left && right) return [variant, 6];
  if (!top && bottom && left && !right) return [variant, 7];
  if (!top && !bottom && !left && right) return [variant, 8];
  if (!top && !bottom && left && !right) return [variant, 9];
  if (!top && !bottom && !left && !right) return [variant, 10];
  return [5, 12];
}

function drawParallaxBackdropLayer(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  layer: VisualThemeLayer,
  entry: AtlasEntry,
  frame: number,
  camera: CameraBounds,
): void {
  const time = frame / 60;
  const scrollX = layer.scrollX ?? 1;
  const scrollY = layer.scrollY ?? 1;
  // Vanilla Parallax.Render draws at screen (Position - Camera * Scroll);
  // under the world transform the anchor is Position + Camera * (1 - Scroll).
  const anchorX = (layer.speedX ?? 0) * time + camera.x * (1 - scrollX);
  const anchorY =
    (layer.y ?? 0) + (layer.speedY ?? 0) * time + camera.y * (1 - scrollY);
  const drawAt = (x: number, y: number) =>
    context.drawImage(
      assets.image,
      entry.x,
      entry.y,
      entry.width,
      entry.height,
      x + entry.drawOffsetX,
      y + entry.drawOffsetY,
      entry.frameWidth,
      entry.frameHeight,
    );
  context.save();
  context.globalAlpha = layer.opacity ?? 1;
  if (layer.loopX || layer.loopY) {
    const firstX = layer.loopX
      ? anchorX + Math.floor((camera.x - anchorX) / entry.frameWidth) * entry.frameWidth
      : anchorX;
    for (let x = firstX; x < camera.x + camera.width; x += entry.frameWidth) {
      const firstY = layer.loopY
        ? anchorY + Math.floor((camera.y - anchorY) / entry.frameHeight) * entry.frameHeight
        : anchorY;
      for (let y = firstY; y < camera.y + camera.height; y += entry.frameHeight) {
        drawAt(x, y);
        if (!layer.loopY) break;
      }
      if (!layer.loopX) break;
    }
  } else {
    drawAt(anchorX, anchorY);
  }
  context.restore();
}

function drawBackdropLayer(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  map: GymMap,
  layer: VisualThemeLayer,
  frame: number,
  camera: CameraBounds,
): void {
  const entry = assets.entries[layer.key];
  if (!entry) return;
  if (layer.scrollX !== undefined || layer.scrollY !== undefined) {
    drawParallaxBackdropLayer(context, assets, layer, entry, frame, camera);
    return;
  }
  if (layer.repeat) {
    context.save();
    context.globalAlpha = layer.opacity ?? 1;
    context.beginPath();
    context.rect(
      map.bounds.x,
      map.bounds.y,
      map.bounds.width,
      map.bounds.height,
    );
    context.clip();
    for (
      let y = map.bounds.y;
      y < map.bounds.y + map.bounds.height;
      y += entry.height
    ) {
      for (
        let x = map.bounds.x;
        x < map.bounds.x + map.bounds.width;
        x += entry.width
      ) {
        context.drawImage(
          assets.image,
          entry.x,
          entry.y,
          entry.width,
          entry.height,
          x,
          y,
          entry.width,
          entry.height,
        );
      }
    }
    context.restore();
    return;
  }
  const scale = Math.max(map.bounds.width / 320, map.bounds.height / 180);
  const frameX =
    map.bounds.x + (map.bounds.width - entry.frameWidth * scale) / 2;
  const frameY =
    layer.y === undefined
      ? map.bounds.y + map.bounds.height - entry.frameHeight * scale
      : map.bounds.y + layer.y * scale;
  context.save();
  context.globalAlpha = layer.opacity ?? 1;
  context.drawImage(
    assets.image,
    entry.x,
    entry.y,
    entry.width,
    entry.height,
    frameX + entry.drawOffsetX * scale,
    frameY + entry.drawOffsetY * scale,
    entry.width * scale,
    entry.height * scale,
  );
  context.restore();
}

