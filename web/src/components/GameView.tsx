      const color = palette[Math.floor(pseudo(index * 17.41) * palette.length)];
      const tile = dreamParticleTexture(assets, sourceX, color);
      if (tile)
        context.drawImage(tile, Math.round(px - 3.5), Math.round(py - 3.5));
