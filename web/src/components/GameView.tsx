function drawRefill(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  entity: MapEntity,
  frame: number,
  state: SimState,
  kindIndex: number,
): void {
  const runtime = state.refills?.[kindIndex];
  if (runtime?.removed) return;
  const box = entity.bounds;
  const centerX = box.x + box.width / 2;
  const centerY = box.y + box.height / 2;
  const twoDash = runtime?.two_dashes ?? entity.direction.x !== 0;
  const prefix = twoDash ? "objects/refillTwo" : "objects/refill";
  // Vanilla Refill bobs on a 0.6 Hz SineWave with a per-entity random phase.
  const seed = pseudo(box.x * 0.19 + box.y * 0.23 + kindIndex * 5.7);
  const bob = Math.sin((frame / 60) * 0.6 * Math.PI * 2 + seed * Math.PI * 2) * 2;
  const drawCentered = (key: string, yOffset = 0) => {
    const entry = assets.entries[key];
    if (!entry) return false;
    const destination = centeredAtlasEntryDestination(
      entry,
      centerX,
      centerY + bob + yOffset,
    );
    context.drawImage(
      assets.image,
      entry.x,
      entry.y,
      entry.width,
      entry.height,
      destination.x,
      destination.y,
      destination.width,
      destination.height,
    );
    return true;
  };
  const active = runtime?.collidable ?? true;
  if (!active) {
    // Consumed: only the respawn outline remains (Refill.Render shows
    // sprite.DrawOutline, then the outline image once collected).
    drawCentered(prefix + "/outline");
    return;
  }
  const idles = frames(assets, prefix + "/idle");
  if (idles.length === 0) return;
  // Sprite.AddLoop("idle", "", 0.1f): six ticks per frame.
  const key = idles[Math.floor(frame / 6) % idles.length];
  if (!drawCentered(key)) return;
  // A flash sequence plays every two seconds (0.05s per frame).
  const flashTicks = Math.floor(frame / 3) % 40;
  if (flashTicks < 6) {
    const flashes = frames(assets, prefix + "/flash");
    const flashKey = flashes[flashTicks % flashes.length];
    if (flashKey) drawCentered(flashKey);
  }
}

export function centeredAtlasEntryDestination(
  entry: Pick<
    AtlasEntry,
    "width" | "height" | "drawOffsetX" | "drawOffsetY" | "frameWidth" | "frameHeight"
  >,
  centerX: number,
  centerY: number,
): { x: number; y: number; width: number; height: number } {
  return {
    x: Math.round(centerX - entry.frameWidth / 2 + entry.drawOffsetX),
    y: Math.round(centerY - entry.frameHeight / 2 + entry.drawOffsetY),
    width: entry.width,
    height: entry.height,
  };
}

function drawFallingBlock(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  entity: MapEntity,
  state: SimState,
  kindIndex: number,
  theme: VisualTheme,
): void {
  const runtime = state.falling_blocks?.[kindIndex];
  if (runtime?.removed) return;
  const box = runtimeEntityBounds(entity, state, kindIndex);
  // Vanilla FallingBlock is GFX.FGAutotiler.GenerateBox(tiletype, w/8, h/8):
  // the box grid is autotiled with the tiletype char's tileset (border masks,
  // padded inner edge, center fill), exactly like the in-game block skin.
  const def: TileSetDef = entity.tile
    ? theme.tilesets?.[entity.tile] ?? {
        path: theme.tileset,
        scan: theme.tileScan,
        ignores: theme.tileIgnores,
        rules: theme.tileRules ?? undefined,
        center: theme.centerTile,
        padded: theme.paddedTile,
      }
    : {
        path: theme.tileset,
        scan: theme.tileScan,
        ignores: theme.tileIgnores,
        rules: theme.tileRules ?? undefined,
        center: theme.centerTile,
        padded: theme.paddedTile,
      };
  const tilesetKey = def.path ?? theme.tileset;
  const tileset = assets.entries[tilesetKey];
  if (tileset) {
    const columns = Math.max(1, Math.floor(box.width / 8));
    const rows = Math.max(1, Math.floor(box.height / 8));
    const boxGrid = Array.from({ length: rows }, () =>
      Array.from({ length: columns }, () => "1"),
    );
    for (let y = 0; y < rows; y += 1) {
      for (let x = 0; x < columns; x += 1) {
        const [tileX, tileY] = autotileBox(boxGrid, x, y, def);
        context.drawImage(
          assets.image,
          tileset.x + tileX * 8,
          tileset.y + tileY * 8,
          8,
          8,
          box.x + x * 8,
          box.y + y * 8,
          8,
          8,
        );
      }
    }
    return;
  }
  context.fillStyle = "#3f4a5a";
  context.fillRect(box.x, box.y, box.width, box.height);
  context.strokeStyle = "#8a97a8";
  context.lineWidth = 1;
  context.strokeRect(
    box.x + 0.5,
    box.y + 0.5,
    Math.max(0, box.width - 1),
    Math.max(0, box.height - 1),
  );
}

function drawUnknownEntity(
  context: CanvasRenderingContext2D,
  entity: MapEntity,
): void {
  const box = entity.bounds;
  context.fillStyle = "rgba(255, 0, 180, .18)";
  context.fillRect(
    box.x,
    box.y,
    Math.max(8, box.width),
    Math.max(8, box.height),
  );
  context.strokeStyle = "#ff4fc3";
  context.lineWidth = 1;
  context.strokeRect(
    box.x + 0.5,
    box.y + 0.5,
    Math.max(7, box.width - 1),
    Math.max(7, box.height - 1),
  );
  context.fillStyle = "#ffffff";
  context.font = "6px monospace";
  context.textBaseline = "bottom";
  context.fillText(entity.name || entity.kind, box.x + 1, box.y - 1);
}

function drawEntity(
  context: CanvasRenderingContext2D,
  assets: GameAssets,
  entity: MapEntity,
  frame: number,
  state: SimState,
  kindIndex: number,
  entityIndex: number,
  theme: VisualTheme,
): void {
  const box = entity.bounds;
  if (entity.kind === "spikes") {
    drawSpikes(context, assets, entity, theme.spike);
  } else if (entity.kind === "jump_thru") {
    const entry = assets.entries["objects/jumpthru/wood"];
    if (!entry) return;
    for (let x = box.x; x < box.x + box.width; x += 8)
      context.drawImage(
        assets.image,
        entry.x + 8,
        entry.y,
        8,
        Math.min(8, entry.height),
        x,
        box.y,
        8,
        Math.min(8, entry.height),
      );
  } else if (entity.kind === "water") {
    drawWater(context, assets, entity, frame);
  } else if (entity.kind === "dream_block") {
    drawDreamBlock(context, assets, entity, frame, state.can_dream_dash);
  } else if (entity.kind === "booster" || entity.kind === "red_booster") {
    drawBooster(context, assets, entity, frame, state);
  } else if (entity.kind === "fly_feather") {
    drawFlyFeather(context, assets, entity, frame, state);
  } else if (entity.kind === "bumper") {
    drawBumper(context, assets, entity, frame, state);
  } else if (entity.kind === "ice_ball") {
    drawIceBall(context, assets, entity, frame, state);
  } else if (entity.kind === "puffer") {
    drawPuffer(context, assets, entity, frame, state);
  } else if (entity.kind === "angry_oshiro") {
    drawAngryOshiro(context, assets, entity, frame, state);
  } else if (entity.kind === "seeker") {
    drawSeeker(context, assets, entity, frame, state);
  } else if (entity.kind === "snowball") {
    drawSnowball(context, assets, entity, frame, state);
  } else if (entity.kind === "cloud") {
    drawCloud(context, assets, entity, state, kindIndex);
  } else if (entity.kind === "badeline_boost") {
    drawBadelineBoost(context, assets, entity, frame, state);
  } else if (entity.kind === "spring") {
    drawSpring(context, assets, entity);
  } else if (entity.kind === "strawberry") {
    if (!strawberryIsPicked(state, entityIndex))
      drawStrawberry(context, assets, entity, frame);
  } else if (entity.kind === "refill") {
    drawRefill(context, assets, entity, frame, state, kindIndex);
  } else if (entity.kind === "falling_block") {
    drawFallingBlock(context, assets, entity, state, kindIndex, theme);
  } else if (entity.kind === "bounce_block") {
    drawBounceBlock(context, assets, entity, frame, state, kindIndex);
  } else if (entity.kind === "theo_crystal") {
    drawTheoCrystal(context, assets, entity, state, kindIndex);
  } else if (entity.kind === "glider") {
    drawGlider(context, assets, entity, frame, state, kindIndex);
  } else if (entity.kind === "heart_gem") {
    drawHeartGem(context, assets, entity, frame, state, kindIndex);
  } else if (entity.kind === "zip_mover") {
    drawZipMover(context, assets, entity, frame, state, kindIndex);
  } else if (entity.kind === "move_block") {
    drawMoveBlock(context, assets, entity, state, kindIndex);
  } else if (entity.kind === "cassette_block") {
    drawCassetteBlock(context, assets, entity, state, kindIndex);
  } else if (entity.kind === "crystal_static_spinner") {
    // Drawn by collectSpinnerDrawItems/drawSpinnerItems (one two-pass group:
    // black outline behind, tinted art on top), not inside the entity loop.
  } else if (entity.kind === "moving_solid") {
    drawMovingSolid(context, entity, state, kindIndex);
  } else if (entity.kind !== "wind") {
    drawUnknownEntity(context, entity);
  }
}

/** Refs the live loop updates every simulated tick without a React commit.
 * GameView's own rAF loop reads these so the canvas can keep running at the
 * display cadence even when React state updates are throttled. */
export interface LiveRenderRefs {
  /** Latest live player state. */
  state: RefObject<SimState>;
  /** Latest live frame number. */
  frame: RefObject<number>;
  /** Latest live history window (mutated in place by the host). */
  history: RefObject<{ startFrame: number; states: SimState[] }>;
  /** Latest live staleness flag (optional; defaults to the prop value). */
  stale?: RefObject<boolean>;
}

/** Everything paintGame needs to draw one canvas frame. */
interface GameViewDrawInput {
  assets: GameAssets;
  map: GymMap;
  theme: VisualTheme;
  frame: number;
  state: SimState;
  states: readonly (SimState | undefined)[];
  stateFrameOffset: number;
  stale: boolean;
  camera: CameraBounds;
  cameraPosition?: Vec2;
  cameraViewport?: CameraBounds;
  tileLayer: HTMLCanvasElement | undefined;
  /** Static spinner groups pre-rendered per group; null falls back per-frame. */
  spinnerGroups: SpinnerGroup[] | null;
  entityKindIndices: readonly number[];
  staticMoverAttachments: readonly StaticMoverAttachment[];
  viewportRevision: number;
}

function paintGame(
  canvas: HTMLCanvasElement,
  context: CanvasRenderingContext2D,
  dpr: number,
  input: GameViewDrawInput,
): void {
  const rect = canvas.getBoundingClientRect();
  const width = Math.round(rect.width * dpr);
  const height = Math.round(rect.height * dpr);
  // Resizing clears the canvas and resets the transform; only do it when the
  // backing store actually changed so steady-state frames skip the reset.
  if (canvas.width !== width || canvas.height !== height) {
    canvas.width = width;
    canvas.height = height;
    context.setTransform(dpr, 0, 0, dpr, 0, 0);
  }
  const {
    assets,
    map,
    theme,
    frame,
    state,
    states,
    stateFrameOffset,
    stale,
    camera,
    tileLayer,
  } = input;
  context.imageSmoothingEnabled = false;

  const scale = Math.min(
    rect.width / camera.width,
    rect.height / camera.height,
  );
  const offsetX = (rect.width - camera.width * scale) / 2;
  const offsetY = (rect.height - camera.height * scale) / 2;
  context.fillStyle = "#000000";
  context.fillRect(0, 0, rect.width, rect.height);

  context.save();
  context.translate(
    offsetX - camera.x * scale,
    offsetY - camera.y * scale,
  );
  context.scale(scale, scale);
  // The playfield is the room rect; everything outside it stays black.
  context.beginPath();
  context.rect(map.bounds.x, map.bounds.y, map.bounds.width, map.bounds.height);
  context.clip();
  drawThemeBackground(context, assets, map, theme, frame, camera);
  if (tileLayer) context.drawImage(tileLayer, map.bounds.x, map.bounds.y);
  const spinnerGroups = input.spinnerGroups;
  if (spinnerGroups && spinnersAreStatic(map, state)) {
    // Static crystals: blit one pre-rendered canvas per connected group
    // (the five outline passes are baked in), instead of re-collecting items
    // and re-issuing every drawImage on each frame.
    for (const group of spinnerGroups) {
      if (!spinnerGroupInView(group, camera)) continue;
      let canvas = group.canvases.get("static");
      if (!canvas) {
        canvas = renderSpinnerGroupCanvas(group, assets);
        group.canvases.set("static", canvas);
      }
      context.drawImage(canvas, group.origin.x, group.origin.y);
    }
  } else {
    const spinnerItems = collectSpinnerDrawItems(
      assets,
      map,
      frame,
      state,
      theme,
      camera,
    );
    drawSpinnerItems(context, assets, spinnerItems);
  }
  const attachedEntityBounds = runtimeAttachedEntityBounds(
    map,
    state,
    input.staticMoverAttachments,
  );
  for (const [entityIndex, entity] of map.entities.entries()) {
    const kindIndex = input.entityKindIndices[entityIndex] ?? 0;
    const renderedEntity = attachedEntityBounds.has(entityIndex)
      ? { ...entity, bounds: attachedEntityBounds.get(entityIndex)! }
      : entity;
    drawEntity(
      context,
      assets,
      renderedEntity,
      frame,
      state,
      kindIndex,
      entityIndex,
      theme,
    );
  }
  context.globalAlpha = stale ? 0.45 : 1;
  drawPlayerParticles(context, assets, states, frame, stateFrameOffset);
  drawPlayerTrail(context, assets, states, frame, stateFrameOffset);
  drawPlayer(context, assets, states, state, frame, stateFrameOffset);
  drawWind(context, assets, map, state, frame);
  context.restore();
}

function gameViewDrawChanged(
  next: GameViewDrawInput,
  last: GameViewDrawInput | null,
): boolean {
  if (!last) return true;
  return (
    next.assets !== last.assets ||
    next.map !== last.map ||
    next.theme !== last.theme ||
    next.frame !== last.frame ||
    next.state !== last.state ||
    next.states !== last.states ||
    next.stateFrameOffset !== last.stateFrameOffset ||
    next.stale !== last.stale ||
    next.cameraPosition !== last.cameraPosition ||
    next.cameraViewport !== last.cameraViewport ||
    next.tileLayer !== last.tileLayer ||
    next.spinnerGroups !== last.spinnerGroups ||
    next.entityKindIndices !== last.entityKindIndices ||
    next.staticMoverAttachments !== last.staticMoverAttachments ||
    next.viewportRevision !== last.viewportRevision ||
    next.camera.x !== last.camera.x ||
    next.camera.y !== last.camera.y ||
    next.camera.width !== last.camera.width ||
    next.camera.height !== last.camera.height
  );
}

export const GameView = memo(function GameView({
  map,
  state,
  states,
  stateFrameOffset = 0,
  frame,
  stale,
  theme,
  cameraPosition,
  cameraViewport,
  children,
  liveRefs,
}: {
  map: GymMap;
  state: SimState;
  states: readonly (SimState | undefined)[];
  stateFrameOffset?: number;
  frame: number;
  stale: boolean;
  theme: VisualTheme;
  /** Manual top-left camera position. Omit to render SimState.camera. */
  cameraPosition?: Vec2;
  /** Editor-only viewport override that may zoom beyond Celeste's 320x180 camera. */
  cameraViewport?: CameraBounds;
  children?:
    | ReactNode
    | ((viewport: GameViewViewport) => ReactNode);
  /** Live-render refs: when present, the rAF loop draws from these refs
   * (updated by the host without React commits) instead of the props. */
  liveRefs?: LiveRenderRefs;
}) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const [assets, setAssets] = useState<GameAssets | null>(null);
  const [themeAssets, setThemeAssets] = useState<GameAssets | null>(null);
  const [viewportRevision, setViewportRevision] = useState(0);
  const solidGrid = useMemo(() => buildSolidGrid(map), [map]);
  const mergedAssets = useMemo(
    () => (assets ? (themeAssets ? mergeGameAssets(assets, themeAssets) : assets) : null),
    [assets, themeAssets],
  );
  const tileLayer = useMemo(
    () =>
      mergedAssets ? buildTileLayer(mergedAssets, map, solidGrid, theme) : undefined,
    [mergedAssets, map, solidGrid, theme],
  );
  const spinnerGroups = useMemo(
    () => (mergedAssets ? buildSpinnerGroups(mergedAssets, map, theme) : null),
    [mergedAssets, map, theme],
  );
  const kindIndices = useMemo(() => entityKindIndices(map), [map]);
  const staticMoverAttachments = useMemo(
    () => buildStaticMoverAttachments(map),
    [map],
  );
  const camera = cameraViewport
    ? clampCameraViewport(map, cameraViewport)
    : cameraBounds(
        cameraPosition
          ? clampCameraPosition(map, cameraPosition)
          : stateCameraPosition(map, state),
      );

  useEffect(() => {
    void loadAssets().then(setAssets);
  }, []);
  useEffect(() => {
    let cancelled = false;
    setThemeAssets(null);
    if (!theme.atlasUrl) return;
    void loadThemeAtlas(theme.atlasUrl)
      .then((atlas) => {
        if (!cancelled) setThemeAssets(atlas);
      })
      .catch(() => {
        // The theme atlas is optional; the base atlas still covers fallbacks.
      });
    return () => {
      cancelled = true;
    };
  }, [theme]);
  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const observer = new ResizeObserver(() =>
      setViewportRevision((value) => value + 1),
    );
    observer.observe(canvas);
    return () => observer.disconnect();
  }, []);

  // Latest draw inputs, refreshed on every render. The rAF loop below reads
  // this instead of re-running a full redraw inside a props-driven effect, so
  // the canvas work is decoupled from React commit timing and frequency.
  const drawInputRef = useRef<GameViewDrawInput | null>(null);
  drawInputRef.current = mergedAssets
    ? {
        assets: mergedAssets,
        map,
        theme,
        frame,
        state,
        states,
        stateFrameOffset,
        stale,
        camera,
        cameraPosition,
        cameraViewport,
        tileLayer,
        spinnerGroups,
        entityKindIndices: kindIndices,
        staticMoverAttachments,
        viewportRevision,
      }
    : null;

  const drawSnapshotForFrame = (
    last: GameViewDrawInput | null,
  ): GameViewDrawInput | null => {
    const base = drawInputRef.current;
    if (!base) return null;
    if (!liveRefs) return base;
    const liveState = liveRefs.state.current;
    const history = liveRefs.history.current;
    const liveFrame = liveRefs.frame.current;
    const liveStale = liveRefs.stale?.current ?? base.stale;
    if (
      last &&
      base.assets === last.assets &&
      base.map === last.map &&
      base.theme === last.theme &&
      base.tileLayer === last.tileLayer &&
      base.spinnerGroups === last.spinnerGroups &&
      base.entityKindIndices === last.entityKindIndices &&
      base.staticMoverAttachments === last.staticMoverAttachments &&
      base.viewportRevision === last.viewportRevision &&
      base.cameraPosition === last.cameraPosition &&
      base.cameraViewport === last.cameraViewport &&
      liveState === last.state &&
      liveFrame === last.frame &&
      history.states === last.states &&
      history.startFrame === last.stateFrameOffset &&
      liveStale === last.stale
    )
      return last;
    return {
      ...base,
      state: liveState,
      frame: liveFrame,
      states: history.states,
      stateFrameOffset: history.startFrame,
      stale: liveStale,
      camera: base.cameraViewport
        ? clampCameraViewport(base.map, base.cameraViewport)
        : cameraBounds(
            base.cameraPosition
              ? clampCameraPosition(base.map, base.cameraPosition)
              : stateCameraPosition(base.map, liveState),
          ),
    };
  };

  useEffect(() => {
    if (!mergedAssets) return;
    const canvas = canvasRef.current;
    if (!canvas) return;
    const context = canvas.getContext("2d");
    if (!context) return;
    const dpr = window.devicePixelRatio || 1;
    let animation = 0;
    let last: GameViewDrawInput | null = null;
    const tick = () => {
      animation = requestAnimationFrame(tick);
      const snapshot = drawSnapshotForFrame(last);
      if (!snapshot) return;
      if (snapshot === last) return;
      if (!gameViewDrawChanged(snapshot, last)) return;
      paintGame(canvas, context, dpr, snapshot);
      last = snapshot;
    };
    animation = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(animation);
  }, [mergedAssets, liveRefs]);

  return (
    <div className="game-screen">
      <canvas
        ref={canvasRef}
        aria-label={`CelesteGymPlayground 原版资源渲染画面 · ${theme.label}`}
      />
      {typeof children === "function"
        ? children({
            width: canvasRef.current?.clientWidth ?? 0,
            height: canvasRef.current?.clientHeight ?? 0,
            camera,
          })
        : children}
      <div className="screen-vignette" />
      <div className="screen-noise" />
      {!assets && (
        <div className="recompute-flag">
          <span />
          加载 Gameplay atlas
        </div>
      )}
      {assets && stale && (
        <div className="recompute-flag">
          <span />
          等待重算
        </div>
      )}
    </div>
  );
});


